import {test,expect} from '@playwright/test';
const url='pilotes/microduck-introduction-softmax-r1/index.html';
test('premier transfert incorrect : première tentative conservée sans dévoiler le corrigé',async({page})=>{
 await page.goto(url);
 await page.locator('[data-guess="no"]').click();
 await page.locator('#why').fill('Les scores doivent être convertis en une distribution normalisée.');
 await page.locator('#go2').click();await page.locator('[data-predict="flat"]').click();await page.locator('#go3').click();
 await page.locator('#pA').fill('0.665');await page.locator('#checkPA').click();
 await page.locator('[data-shift="same"]').click();await page.locator('#go4').click();
 await page.locator('#transferD').fill('0.900');
 await page.locator('#transferE').fill('0.050');
 await page.locator('#transferF').fill('0.050');
 await page.locator('#transferReason').fill('Je calcule des exponentielles puis je normalise et je justifie la somme.');
 await page.locator('#checkTransfer').click();
 await expect(page.locator('#attemptA')).toContainText('Première tentative enregistrée (calcul à reprendre)');
 await expect(page.locator('#transferFeedback')).not.toContainText('0,629');
 await expect(page.locator('#go5')).toBeDisabled();
 await page.locator('#checkTransfer').click();
 await expect(page.locator('#transferFeedback')).toContainText('Valeurs de remédiation');
 await expect(page.locator('#evidenceState')).toContainText('2 soumission(s)');
});
test('export : les réponses A, B et C restent locales et sont téléchargeables en JSON',async({page})=>{
 await page.goto(url);
 await page.locator('[data-guess="no"]').click();
 await page.locator('#why').fill('Les scores doivent être convertis avant la normalisation.');
 await page.locator('#go2').click();await page.locator('[data-predict="flat"]').click();await page.locator('#go3').click();
 await page.locator('#pA').fill('0.665');await page.locator('#checkPA').click();
 await page.locator('[data-shift="same"]').click();await page.locator('#go4').click();
 for(const [id,value] of [['transferD','0.629'],['transferE','0.231'],['transferF','0.140']])await page.locator('#'+id).fill(value);
 await page.locator('#transferReason').fill('Les probabilités correspondent aux exponentielles normalisées, pas à la vérité.');
 await page.locator('#checkTransfer').click();
 await page.locator('#inverseTemp').fill('1.44');
 await page.locator('#inverseReason').fill('Pour vérifier je calcule à nouveau les poids à cette température et leur somme.');
 await page.locator('#checkInverse').click();
 await page.locator('#go5').click();
 await page.locator('#profile').selectOption('enseignant');
 await page.locator('#criticalReason').fill('Je peux vérifier une implémentation par des sommes, des valeurs finies et des tests de translation des scores.');
 await page.locator('#teacherReason').fill('Je repère deux conceptions erronées puis je propose une remédiation fondée sur des calculs contrôlés. Je fais construire une évaluation indépendante qui exige une justification et une tolérance numérique.');
 await page.locator('#showRubric').click();
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#exportEvidence').click();
 const download=await downloadPromise;
 expect(download.suggestedFilename()).toBe('llm-academy-softmax-trace.json');
 const stream=await download.createReadStream();
 const chunks:Buffer[]=[];for await(const chunk of stream)chunks.push(Buffer.from(chunk));
 const data=JSON.parse(Buffer.concat(chunks).toString('utf8'));
 expect(data.attempts.A).toHaveLength(1);
 expect(data.attempts.B).toHaveLength(1);
 expect(data.attempts.C).toHaveLength(1);
 expect(data.profile).toBe('enseignant');
 expect(data.attempts.A[0].numericallyCorrect).toBe(true);
 await page.locator('#resetEvidence').click();
 await expect(page.locator('#evidenceState')).toContainText('0 soumission(s)');
});
